#!/usr/bin/env python3
"""Regenerate the machine-derived sections of each crate's README.md.

Each section lives between a pair of markers,

    <!-- generated:<name>:begin -->
    ...
    <!-- generated:<name>:end -->

and only the text between them is rewritten; everything outside the markers is
hand-written and left byte for byte. A README missing a section gets it appended
at the end; a crate with no README gets one with its manifest description as
the opening paragraph.

Sections: `facts` (version, MSRV, license, registry links), `layout` (the
tracked `src/` tree, each Rust file with the first sentence of its `//!` doc,
and the targets the manifest declares), `stats` (line counts and item counts),
`docs` (every tracked Markdown file in the crate other than the README),
`features`, `dependencies` (internal dependencies and dependents), `adrs` (the
ADRs under `docs/adr/` that name the crate) and `benchmarks` (the latest
Criterion numbers `bench-update.yml` stored on the `perf-baselines` branch).

The population is the git index (`git ls-files`), so an untracked file is not
counted and a run on a clean checkout is reproducible. Output carries no
timestamp of its own: two runs on the same commit and the same `perf-baselines`
head produce identical files.

Exit 0 when nothing is stale (`--check`) or after writing (`--write`), 1 when
`--check` finds a stale README, 2 when the inputs cannot be read or a README's
markers are malformed.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

EXIT_OK = 0
EXIT_STALE = 1
EXIT_ERROR = 2

SECTIONS = ("facts", "layout", "stats", "docs", "features", "dependencies", "adrs", "benchmarks")
MARKER = re.compile(r"<!-- generated:([A-Za-z0-9_-]+):(begin|end) -->")
INTRO = (
    "## Crate reference\n\n"
    "The sections below are generated by `scripts/crate-readme.py` from the source tree and are "
    "refreshed after pushes to `main`. Text between the `generated` markers is overwritten; edit "
    "the source or the script instead.\n"
)
DETAILS_THRESHOLD = 12
BENCH_WORKFLOW = Path(".github/workflows/bench-update.yml")
BENCH_INVOCATION = re.compile(r"cargo bench -p (\S+) --bench (\S+)")
BENCH_NAME_LITERAL = re.compile(r"(?:benchmark_group|bench_function)\(\s*\"([^\"]+)\"")


class InputError(Exception):
    """The generator could not read an input it needs; nothing was written."""


# --------------------------------------------------------------------------- Rust scanning


RAW_STRING_START = re.compile(r"[bc]?r(#*)\"")
CHAR_LITERAL = re.compile(r"'(?:\\(?:x[0-9A-Fa-f]{2}|u\{[0-9A-Fa-f_]{1,6}\}|.)|[^\\'\n])'")
TEST_ATTR = re.compile(r"#\[\s*(?:[A-Za-z_][A-Za-z0-9_]*::)*test\b[^\]]*\]")
PUB_ITEM = re.compile(
    r"^\s*pub\s+(?:(?:unsafe|async|const|default|extern(?:\s+\"\")?)\s+)*"
    r"(?:fn|struct|enum|trait|type|const|static|mod|use|union)\b"
)
UNSAFE = re.compile(r"\bunsafe\b")


@dataclass
class RustCounts:
    files: int = 0
    code: int = 0
    comment: int = 0
    blank: int = 0
    tests: int = 0
    pub_items: int = 0
    unsafe: int = 0

    def add(self, other: RustCounts) -> None:
        for name in ("files", "code", "comment", "blank", "tests", "pub_items", "unsafe"):
            setattr(self, name, getattr(self, name) + getattr(other, name))


def _is_ident(ch: str) -> bool:
    return ch.isalnum() or ch == "_"


def scan_rust(text: str) -> list[tuple[str, str]]:
    """Classify each line as code, comment or blank, with its code text.

    The code text has comments removed and string and character literal contents
    blanked, so a keyword inside a string or a comment is never counted. A line
    holding any code is code; a line holding only comment text is comment.
    """
    lines: list[tuple[str, str]] = []
    code: list[str] = []
    has_code = False
    has_comment = False
    depth = 0
    in_string = False
    raw_hashes: int | None = None
    i = 0
    n = len(text)

    def end_line() -> None:
        nonlocal code, has_code, has_comment
        kind = "code" if has_code else "comment" if has_comment else "blank"
        lines.append((kind, "".join(code)))
        code = []
        has_code = False
        has_comment = False

    while i < n:
        ch = text[i]
        if ch == "\n":
            end_line()
            i += 1
            continue
        if depth > 0:
            has_comment = True
            if text.startswith("/*", i):
                depth += 1
                i += 2
            elif text.startswith("*/", i):
                depth -= 1
                i += 2
            else:
                i += 1
            continue
        if in_string:
            if not ch.isspace():
                has_code = True
            if raw_hashes is None:
                if ch == "\\" and i + 1 < n and text[i + 1] != "\n":
                    i += 2
                    continue
                if ch == '"':
                    in_string = False
                    code.append('"')
            elif ch == '"' and text.startswith("#" * raw_hashes, i + 1):
                in_string = False
                code.append('"')
                i += 1 + raw_hashes
                continue
            i += 1
            continue
        if ch in " \t\r":
            code.append(ch)
            i += 1
            continue
        if text.startswith("//", i):
            has_comment = True
            newline = text.find("\n", i)
            i = n if newline < 0 else newline
            continue
        if text.startswith("/*", i):
            has_comment = True
            depth = 1
            i += 2
            continue
        has_code = True
        raw = RAW_STRING_START.match(text, i)
        if raw is not None and (i == 0 or not _is_ident(text[i - 1])):
            in_string = True
            raw_hashes = len(raw.group(1))
            code.append('"')
            i = raw.end()
            continue
        if ch == '"':
            in_string = True
            raw_hashes = None
            code.append('"')
            i += 1
            continue
        if ch == "'":
            literal = CHAR_LITERAL.match(text, i)
            if literal is not None:
                code.append("' '")
                i = literal.end()
                continue
        code.append(ch)
        i += 1
    if code or has_code or has_comment:
        end_line()
    return lines


def count_rust(text: str) -> RustCounts:
    counts = RustCounts(files=1)
    for kind, code in scan_rust(text):
        setattr(counts, kind, getattr(counts, kind) + 1)
        if kind != "code":
            continue
        counts.tests += len(TEST_ATTR.findall(code))
        if PUB_ITEM.match(code):
            counts.pub_items += 1
        counts.unsafe += len(UNSAFE.findall(code))
    return counts


SENTENCE_END = re.compile(r"(?<=[.!?])\s+(?=[A-Z0-9`(\[])")
ABBREVIATIONS = ("e.g.", "i.e.", "vs.", "etc.", "cf.", "approx.")
LINK = re.compile(r"\[([^\]]+)\]\([^)]*\)")
INTRA_DOC = re.compile(r"\[(`[^`\]]+`)\]")


def first_sentence(text: str) -> str:
    """First sentence of a file's leading `//!` paragraph, or "" when it has none."""
    paragraph: list[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("//!"):
            body = stripped[3:].strip()
            if not body:
                if paragraph:
                    break
                continue
            if body.startswith("#") and not paragraph:
                return body.lstrip("#").strip()
            paragraph.append(body)
            continue
        if paragraph or not (stripped == "" or stripped.startswith("#![") or stripped.startswith("//")):
            break
    joined = " ".join(paragraph)
    joined = LINK.sub(r"\1", joined)
    joined = INTRA_DOC.sub(r"\1", joined)
    joined = joined.replace("[", "\\[").replace("]", "\\]")
    start = 0
    for match in SENTENCE_END.finditer(joined):
        head = joined[: match.start()]
        if head.endswith(ABBREVIATIONS):
            continue
        return joined[start : match.start()]
    return joined


# --------------------------------------------------------------------------- inputs


@dataclass
class Crate:
    name: str
    directory: str  # repo-relative, e.g. "crates/embed"
    package: dict
    files: list[str] = field(default_factory=list)  # repo-relative tracked paths


def git(root: Path, *args: str) -> bytes:
    result = subprocess.run(["git", "-C", str(root), *args], capture_output=True)
    if result.returncode != 0:
        raise InputError(f"git {' '.join(args)} failed: {result.stderr.decode(errors='replace').strip()}")
    return result.stdout


def load_metadata(root: Path, metadata_path: Path | None) -> dict:
    if metadata_path is not None:
        return json.loads(metadata_path.read_text(encoding="utf-8"))
    result = subprocess.run(
        ["cargo", "metadata", "--no-deps", "--format-version", "1", "--locked", "--offline"],
        cwd=root,
        capture_output=True,
    )
    if result.returncode != 0:
        raise InputError(f"cargo metadata failed: {result.stderr.decode(errors='replace').strip()}")
    return json.loads(result.stdout)


def rel(root: Path, path: str) -> str:
    return Path(os.path.relpath(Path(path).resolve(), root)).as_posix()


def load_crates(root: Path, metadata: dict) -> list[Crate]:
    members = set(metadata.get("workspace_members", []))
    crates: list[Crate] = []
    for package in metadata.get("packages", []):
        if package["id"] not in members:
            continue
        directory = rel(root, str(Path(package["manifest_path"]).parent))
        if not re.fullmatch(r"crates/[^/]+", directory):
            continue
        crates.append(Crate(name=package["name"], directory=directory, package=package))
    if not crates:
        raise InputError("cargo metadata named no workspace member under crates/")
    tracked = git(root, "ls-files", "-z", "--", "crates").decode("utf-8").split("\0")
    by_dir = {crate.directory: crate for crate in crates}
    for path in tracked:
        if not path:
            continue
        parts = path.split("/")
        crate = by_dir.get("/".join(parts[:2]))
        if crate is not None:
            crate.files.append(path)
    for crate in crates:
        crate.files.sort()
    crates.sort(key=lambda crate: crate.directory)
    return crates


@dataclass
class Snapshot:
    arch: str
    commit: str
    date: str
    benches: dict[str, float]


def load_baselines(root: Path, ref: str) -> list[Snapshot]:
    """The newest `history/` snapshot per runner architecture on the baselines ref."""
    names = git(root, "ls-tree", "-z", "--name-only", f"{ref}:history").decode("utf-8").split("\0")
    newest: dict[str, str] = {}
    for name in sorted(n for n in names if n.endswith(".json")):
        parts = name[: -len(".json")].split("_", 2)
        if len(parts) != 3:
            continue
        newest[parts[2]] = name
    if not newest:
        raise InputError(f"{ref}:history holds no snapshot")
    snapshots = []
    for arch in sorted(newest):
        data = json.loads(git(root, "show", f"{ref}:history/{newest[arch]}"))
        if data.get("arch") != arch:
            raise InputError(f"{newest[arch]} records arch {data.get('arch')!r}, not {arch!r}")
        snapshots.append(
            Snapshot(
                arch=arch,
                commit=data["commit"],
                date=data["date"],
                benches={key: value["ns"] for key, value in data["benches"].items()},
            )
        )
    return snapshots


def bench_targets(root: Path, crates: list[Crate]) -> dict[str, list[tuple[str, set[str]]]]:
    """Per crate, the bench targets `bench-update.yml` runs and the group names each defines."""
    workflow = root / BENCH_WORKFLOW
    if not workflow.is_file():
        raise InputError(f"{BENCH_WORKFLOW} is missing")
    invocations = sorted(set(BENCH_INVOCATION.findall(workflow.read_text(encoding="utf-8"))))
    if not invocations:
        raise InputError(f"no `cargo bench -p <package> --bench <target>` line in {BENCH_WORKFLOW}")
    by_name = {crate.name: crate for crate in crates}
    targets: dict[str, list[tuple[str, set[str]]]] = {}
    for package, bench in invocations:
        crate = by_name.get(package)
        if crate is None:
            raise InputError(f"{BENCH_WORKFLOW} benches {package}, which is not a crate under crates/")
        source = next(
            (t["src_path"] for t in crate.package["targets"] if t["name"] == bench and "bench" in t["kind"]),
            None,
        )
        if source is None:
            raise InputError(f"{package} declares no bench target named {bench}")
        names = set(BENCH_NAME_LITERAL.findall(Path(source).read_text(encoding="utf-8")))
        targets.setdefault(crate.name, []).append((bench, names))
    return targets


# --------------------------------------------------------------------------- Markdown helpers


def table(headers: list[str], rows: list[list[str]]) -> str:
    widths = [max(len(headers[i]), *(len(row[i]) for row in rows), 3) for i in range(len(headers))]
    out = ["| " + " | ".join(h.ljust(w) for h, w in zip(headers, widths)) + " |"]
    out.append("| " + " | ".join("-" * w for w in widths) + " |")
    for row in rows:
        out.append("| " + " | ".join(c.ljust(w) for c, w in zip(row, widths)) + " |")
    return "\n".join(out)


def collapsible(summary: str, body: str, count: int) -> str:
    if count <= DETAILS_THRESHOLD:
        return body
    return f"<details>\n<summary>{summary}</summary>\n\n{body}\n\n</details>"


def markdown_title(path: Path) -> str | None:
    in_fence = False
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        elif not in_fence and line.startswith("# "):
            return line[2:].strip().rstrip("#").strip()
    return None


def format_ns(ns: float) -> str:
    if ns >= 1e6:
        return f"{ns / 1e6:.2f} ms"
    if ns >= 1e3:
        return f"{ns / 1e3:.2f} µs"
    return f"{ns:.1f} ns"


# --------------------------------------------------------------------------- sections


def section_facts(crate: Crate) -> str:
    package = crate.package
    published = package.get("publish") != []
    items = [
        f"- Version: `{package['version']}`",
        f"- Minimum supported Rust version: `{package.get('rust_version') or 'not declared'}`",
        f"- Edition: `{package.get('edition')}`",
        f"- License: `{package.get('license') or 'not declared'}`",
    ]
    if published:
        items.append(f"- crates.io: <https://crates.io/crates/{crate.name}>")
        items.append(f"- API documentation: <https://docs.rs/{crate.name}>")
    else:
        items.append("- Not published to crates.io (`publish = false`)")
    return "### Facts\n\n" + "\n".join(items)


def section_layout(root: Path, crate: Crate) -> str:
    prefix = crate.directory + "/src/"
    sources = [path for path in crate.files if path.startswith(prefix)]
    entries: list[str] = []
    seen_dirs: set[str] = set()
    for path in sources:
        parts = path[len(prefix) :].split("/")
        for depth in range(len(parts) - 1):
            directory = "/".join(parts[: depth + 1])
            if directory not in seen_dirs:
                seen_dirs.add(directory)
                entries.append("  " * depth + f"- `{parts[depth]}/`")
        line = "  " * (len(parts) - 1) + f"- `{parts[-1]}`"
        if path.endswith(".rs"):
            sentence = first_sentence((root / path).read_text(encoding="utf-8", errors="replace"))
            if sentence:
                line += f": {sentence}"
        entries.append(line)
    out = ["### Source layout", ""]
    out.append(
        "The tracked files under `src/`; each Rust file shows the first sentence of its `//!` "
        "module documentation."
    )
    out.append("")
    if entries:
        out.append(collapsible(f"<code>src/</code>: {len(sources)} files", "\n".join(entries), len(entries)))
    else:
        out.append("No tracked files under `src/`.")
    targets: dict[str, list[str]] = {}
    for target in crate.package["targets"]:
        for kind in target["kind"]:
            label = f"`{target['name']}`"
            required = target.get("required-features") or []
            if required:
                label += " (requires " + ", ".join(f"`{feature}`" for feature in required) + ")"
            targets.setdefault(kind, []).append(label)
    out.append("")
    out.append("Targets declared by the manifest, including the ones Cargo discovers by directory:")
    out.append("")
    order = ["lib", "rlib", "cdylib", "staticlib", "proc-macro", "bin", "example", "test", "bench", "custom-build"]
    kinds = sorted(targets, key=lambda kind: (order.index(kind) if kind in order else len(order), kind))
    for kind in kinds:
        names = sorted(targets[kind])
        out.append(f"- {kind} ({len(names)}): " + ", ".join(names))
    return "\n".join(out)


def section_stats(root: Path, crate: Crate) -> str:
    areas = ["src", "tests", "benches", "examples"]
    counts = {area: RustCounts() for area in areas + ["other"]}
    other_files: dict[str, list[int]] = {}
    for path in crate.files:
        relative = path[len(crate.directory) + 1 :]
        top = relative.split("/", 1)[0] if "/" in relative else ""
        file_path = root / path
        if path.endswith(".rs"):
            area = top if top in areas else "other"
            counts[area].add(count_rust(file_path.read_text(encoding="utf-8", errors="replace")))
        elif relative != "README.md":
            extension = Path(path).suffix or Path(path).name
            bucket = other_files.setdefault(extension, [0, 0])
            bucket[0] += 1
            bucket[1] += file_path.stat().st_size
    total = RustCounts()
    rows = []
    for area in areas + ["other"]:
        area_counts = counts[area]
        if area_counts.files == 0:
            continue
        total.add(area_counts)
        label = f"`{area}/`" if area != "other" else "other"
        rows.append(_stats_row(label, area_counts))
    out = ["### Statistics", ""]
    if rows:
        rows.append(_stats_row("total", total))
        out.append(
            "Rust lines by kind (code, comment, blank; doc comments count as comment), test "
            "functions (`#[test]` and `#[<runtime>::test]` attributes), items declared `pub` "
            "(not `pub(crate)`; reachability through private modules is not resolved) and "
            "occurrences of the `unsafe` keyword outside comments and strings."
        )
        out.append("")
        out.append(
            table(["Area", "Files", "Code", "Comment", "Blank", "Tests", "`pub` items", "`unsafe`"], rows)
        )
    else:
        out.append("No tracked Rust files.")
    if other_files:
        out.append("")
        out.append("Other tracked files (the README excluded):")
        out.append("")
        out.append(
            table(
                ["Extension", "Files", "Size"],
                [
                    [f"`{ext}`", str(files), _size(size)]
                    for ext, (files, size) in sorted(other_files.items())
                ],
            )
        )
    return "\n".join(out)


def _stats_row(label: str, counts: RustCounts) -> list[str]:
    return [
        label,
        str(counts.files),
        str(counts.code),
        str(counts.comment),
        str(counts.blank),
        str(counts.tests),
        str(counts.pub_items),
        str(counts.unsafe),
    ]


def _size(size: int) -> str:
    if size >= 1024 * 1024:
        return f"{size / (1024 * 1024):.1f} MiB"
    if size >= 1024:
        return f"{size / 1024:.1f} KiB"
    return f"{size} B"


def section_docs(root: Path, crate: Crate) -> str:
    readme = crate.directory + "/README.md"
    documents = [path for path in crate.files if path.endswith(".md") and path != readme]
    out = ["### In-crate documentation", ""]
    if not documents:
        out.append("No Markdown files besides this README.")
        return "\n".join(out)
    items = []
    for path in documents:
        relative = path[len(crate.directory) + 1 :]
        title = markdown_title(root / path) or relative
        title = title.replace("[", "\\[").replace("]", "\\]")
        items.append(f"- [{title}]({relative}) (`{relative}`)")
    out.append(collapsible(f"{len(items)} documents", "\n".join(items), len(items)))
    return "\n".join(out)


FEATURE_KEY = re.compile(r"^\s*\"?([A-Za-z0-9_.-]+)\"?\s*=")


def feature_comments(manifest: Path) -> dict[str, str]:
    """The comment block directly above each key in the manifest's `[features]` table."""
    comments: dict[str, str] = {}
    pending: list[str] = []
    in_features = False
    depth = 0
    for line in manifest.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if depth == 0 and stripped.startswith("["):
            in_features = stripped == "[features]"
            pending = []
            continue
        if not in_features:
            continue
        if depth > 0:
            depth += stripped.count("[") - stripped.count("]")
            continue
        if stripped.startswith("#"):
            pending.append(stripped.lstrip("#").strip())
            continue
        key = FEATURE_KEY.match(line)
        if key is not None:
            text = " ".join(part for part in pending if part)
            if text:
                comments[key.group(1)] = text
            value = line.split("=", 1)[1]
            depth = value.count("[") - value.count("]")
        pending = []
    return comments


def _sentence(text: str) -> str:
    for match in SENTENCE_END.finditer(text):
        if not text[: match.start()].endswith(ABBREVIATIONS):
            return text[: match.start()]
    return text


def section_features(crate: Crate) -> str:
    features = crate.package.get("features", {})
    comments = feature_comments(Path(crate.package["manifest_path"]))
    defaults = set(features.get("default", []))
    out = ["### Features", ""]
    names = sorted(name for name in features if name != "default")
    if not names:
        out.append("The manifest declares no features.")
        return "\n".join(out)
    out.append(
        "Default set: "
        + (", ".join(f"`{name}`" for name in sorted(defaults)) if defaults else "empty")
        + ". Each description is the first sentence of the comment above the feature in `Cargo.toml`."
    )
    out.append("")
    items = []
    for name in names:
        line = f"- `{name}`" + (" (default)" if name in defaults else "") + ":"
        description = comments.get(name)
        if description:
            line += f" {_sentence(description)}"
        enables = features[name]
        line += " Enables " + (", ".join(f"`{entry}`" for entry in enables) if enables else "nothing") + "."
        items.append(line)
    out.append("\n".join(items))
    return "\n".join(out)


def section_dependencies(crate: Crate, crates: list[Crate]) -> str:
    internal = {other.name for other in crates}
    features = crate.package.get("features", {})

    def describe(dependency: dict) -> str:
        notes = []
        if dependency.get("optional"):
            enabling = sorted(
                feature
                for feature, entries in features.items()
                if any(
                    entry in (dependency["name"], f"dep:{dependency['name']}")
                    or entry.startswith(dependency["name"] + "/")
                    for entry in entries
                )
            )
            notes.append(
                "optional, enabled by " + ", ".join(f"`{feature}`" for feature in enabling)
                if enabling
                else "optional"
            )
        if not dependency.get("uses_default_features", True):
            notes.append("no default features")
        if dependency.get("features"):
            notes.append("features " + ", ".join(f"`{feature}`" for feature in dependency["features"]))
        if dependency.get("target"):
            notes.append(f"only on `{dependency['target']}`")
        return f"`{dependency['name']}`" + (f" ({'; '.join(notes)})" if notes else "")

    out = ["### Workspace dependencies", ""]
    kinds = [(None, "Depends on"), ("build", "Build-depends on"), ("dev", "Dev-depends on")]
    for kind, label in kinds:
        deps = sorted(
            (d for d in crate.package["dependencies"] if d["name"] in internal and d.get("kind") == kind),
            key=lambda d: (d["name"], d.get("target") or ""),
        )
        if deps:
            out.append(f"- {label}: " + ", ".join(describe(d) for d in deps))
        elif kind is None:
            out.append(f"- {label}: no other crate in this workspace")
    dependents: dict[str | None, list[str]] = {}
    for other in crates:
        for dependency in other.package["dependencies"]:
            if dependency["name"] != crate.name:
                continue
            label = f"`{other.name}`" + (" (optional)" if dependency.get("optional") else "")
            bucket = dependents.setdefault(dependency.get("kind"), [])
            if label not in bucket:
                bucket.append(label)
    normal = sorted(dependents.get(None, []))
    out.append("- Used by: " + (", ".join(normal) if normal else "no other crate in this workspace"))
    dev = sorted(dependents.get("dev", []))
    if dev:
        out.append("- Used in tests by: " + ", ".join(dev))
    return "\n".join(out)


def section_adrs(root: Path, crate: Crate, adr_files: list[str]) -> str:
    short = crate.directory.split("/", 1)[1]
    pattern = re.compile(
        rf"(?<![\w-]){re.escape(crate.name)}(?![\w-])|(?<![\w/-])crates/{re.escape(short)}/"
    )
    matches = []
    for path in adr_files:
        text = (root / path).read_text(encoding="utf-8", errors="replace")
        if pattern.search(text):
            title = markdown_title(root / path) or Path(path).name
            title = title.replace("[", "\\[").replace("]", "\\]")
            matches.append(f"- [{title}](../../{path})")
    out = ["### Architecture decisions", ""]
    if not matches:
        out.append(f"No ADR under `docs/adr/` names `{crate.name}` or `crates/{short}/`.")
        return "\n".join(out)
    out.append(f"ADRs under `docs/adr/` that name `{crate.name}` or `crates/{short}/`:")
    out.append("")
    out.append(collapsible(f"{len(matches)} ADRs", "\n".join(matches), len(matches)))
    return "\n".join(out)


def section_benchmarks(
    crate: Crate,
    targets: dict[str, list[tuple[str, set[str]]]],
    owners: dict[str, list[str]],
    snapshots: list[Snapshot],
) -> str:
    out = ["### Benchmarks", ""]
    measured = [
        f"`{package}` `{bench}`" for package, benches in sorted(targets.items()) for bench, _ in benches
    ]
    own = targets.get(crate.name, [])
    if not own:
        out.append(
            "No CI benchmark data for this crate: `bench-update.yml` records only "
            + ", ".join(measured)
            + "."
        )
        return "\n".join(out)
    keys = sorted(
        {key for snapshot in snapshots for key in snapshot.benches if owners.get(key.split("/", 1)[0]) == [crate.name]}
    )
    out.append(
        "The newest Criterion point estimates `bench-update.yml` stored on the `perf-baselines` "
        "branch, from "
        + ", ".join(f"the `{bench}` target" for bench, _ in own)
        + ". They come from GitHub-hosted runners and serve as trend data between commits, not as "
        "a performance claim; a claim needs a paired A/B (`make bench-compare`)."
    )
    out.append("")
    for snapshot in snapshots:
        out.append(f"- `{snapshot.arch}`: commit `{snapshot.commit[:12]}`, recorded {snapshot.date}")
    out.append("")
    if not keys:
        out.append("The newest snapshots hold no entry for this crate's benchmark groups.")
        return "\n".join(out)
    rows = []
    for key in keys:
        row = [f"`{key}`"]
        for snapshot in snapshots:
            value = snapshot.benches.get(key)
            row.append(format_ns(value) if value is not None else "n/a")
        rows.append(row)
    body = table(["Benchmark"] + [f"`{s.arch}`" for s in snapshots], rows)
    out.append(collapsible(f"{len(rows)} benchmarks", body, len(rows)))
    return "\n".join(out)


# --------------------------------------------------------------------------- README splicing


def parse_blocks(text: str, path: str) -> dict[str, tuple[int, int]]:
    """Map each section name to the (start, end) span of the text between its markers."""
    blocks: dict[str, tuple[int, int]] = {}
    open_name: str | None = None
    open_end = 0
    for match in MARKER.finditer(text):
        name, edge = match.group(1), match.group(2)
        if name not in SECTIONS:
            raise InputError(f"{path}: unknown generated section {name!r}")
        if edge == "begin":
            if open_name is not None:
                raise InputError(f"{path}: {name!r} begins inside {open_name!r}")
            if name in blocks:
                raise InputError(f"{path}: {name!r} appears twice")
            open_name, open_end = name, match.end()
        else:
            if open_name != name:
                raise InputError(f"{path}: {name!r} ends without a matching begin")
            blocks[name] = (open_end, match.start())
            open_name = None
    if open_name is not None:
        raise InputError(f"{path}: {open_name!r} begins but never ends")
    return blocks


def splice(text: str, path: str, sections: dict[str, str]) -> str:
    blocks = parse_blocks(text, path)
    for name in sorted(blocks, key=lambda n: blocks[n][0], reverse=True):
        if name not in sections:
            continue
        start, end = blocks[name]
        text = text[:start] + "\n\n" + sections[name] + "\n\n" + text[end:]
    missing = [name for name in SECTIONS if name in sections and name not in blocks]
    if missing:
        text = text.rstrip("\n") + "\n\n"
        if not blocks:
            text += INTRO + "\n"
        text += "\n".join(
            f"<!-- generated:{name}:begin -->\n\n{sections[name]}\n\n<!-- generated:{name}:end -->\n"
            for name in missing
        )
    return text


def new_readme(crate: Crate) -> str:
    description = crate.package.get("description") or ""
    return f"# {crate.name}\n\n{description}\n".replace("\n\n\n", "\n\n")


