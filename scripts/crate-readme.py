def render(root: Path, crates: list[Crate], snapshots: list[Snapshot] | None) -> dict[str, str]:
    adr_files = sorted(
        path
        for path in git(root, "ls-files", "-z", "--", "docs/adr").decode("utf-8").split("\0")
        if path.endswith(".md")
    )
    targets: dict[str, list[tuple[str, set[str]]]] = {}
    owners: dict[str, list[str]] = {}
    if snapshots is not None:
        targets = bench_targets(root, crates)
        for name, benches in targets.items():
            for _, groups in benches:
                for group in groups:
                    owners.setdefault(group, [])
                    if name not in owners[group]:
                        owners[group].append(name)
        unowned = sorted(
            {key.split("/", 1)[0] for s in snapshots for key in s.benches} - set(owners)
        )
        for group in unowned:
            print(f"crate-readme: no bench target source names group {group!r}", file=sys.stderr)
        for group, names in sorted(owners.items()):
            if len(names) > 1:
                print(f"crate-readme: group {group!r} is named by {names}; left out", file=sys.stderr)
    outputs: dict[str, str] = {}
    for crate in crates:
        sections = {
            "facts": section_facts(crate),
            "layout": section_layout(root, crate),
            "stats": section_stats(root, crate),
            "docs": section_docs(root, crate),
            "features": section_features(crate),
            "dependencies": section_dependencies(crate, crates),
            "adrs": section_adrs(root, crate, adr_files),
        }
        if snapshots is not None:
            sections["benchmarks"] = section_benchmarks(crate, targets, owners, snapshots)
        readme = root / crate.directory / "README.md"
        current = readme.read_text(encoding="utf-8") if readme.exists() else new_readme(crate)
        outputs[crate.directory + "/README.md"] = splice(current, crate.directory + "/README.md", sections)
    return outputs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="exit 1 if any README is stale")
    mode.add_argument("--write", action="store_true", help="rewrite stale READMEs in place")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--metadata", type=Path, help="`cargo metadata --no-deps` JSON (default: run cargo)")
    parser.add_argument("--baselines-ref", default="origin/perf-baselines")
    parser.add_argument(
        "--no-benchmarks",
        action="store_true",
        help="leave the benchmarks section untouched (no perf-baselines read)",
    )
    parser.add_argument("--crate", action="append", default=[], help="limit to these package names")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        crates = load_crates(root, load_metadata(root, args.metadata))
        snapshots = None if args.no_benchmarks else load_baselines(root, args.baselines_ref)
        outputs = render(root, crates, snapshots)
    except (InputError, OSError, KeyError, ValueError) as error:
        print(f"crate-readme: {error}", file=sys.stderr)
        return EXIT_ERROR
    if args.crate:
        wanted = set(args.crate)
        unknown = wanted - {crate.name for crate in crates}
        if unknown:
            print(f"crate-readme: unknown crate {sorted(unknown)}", file=sys.stderr)
            return EXIT_ERROR
        keep = {crate.directory + "/README.md" for crate in crates if crate.name in wanted}
        outputs = {path: text for path, text in outputs.items() if path in keep}
    stale = []
    for path, text in sorted(outputs.items()):
        target = root / path
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == text:
            continue
        stale.append(path)
        if args.write:
            target.write_text(text, encoding="utf-8")
    verb = "wrote" if args.write else "stale"
    for path in stale:
        print(f"{verb} {path}")
    print(f"crate-readme: {len(outputs)} READMEs, {len(stale)} {verb}")
    return EXIT_STALE if stale and args.check else EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
